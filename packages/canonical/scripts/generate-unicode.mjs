import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const UNICODE_VERSION = '15.1.0';
const SHORT = UNICODE_VERSION.replace(/\.0$/, '');

const source = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : await (await fetch(`https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/DerivedAge.txt`)).text();
if (!source.includes(`DerivedAge-${UNICODE_VERSION}.txt`)) throw new Error(`not DerivedAge.txt for ${UNICODE_VERSION}`);

const isNoncharacter = (cp) => (cp >= 0xfdd0 && cp <= 0xfdef) || (cp & 0xfffe) === 0xfffe;
const ranges = [];
for (const line of source.split('\n')) {
  const m = line.match(/^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;/);
  if (!m) continue;
  const [s, e] = [parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16)];
  let start = -1;
  for (let cp = s; cp <= e + 1; cp++) {
    const keep = cp <= e && !isNoncharacter(cp);
    if (keep && start < 0) start = cp;
    if (!keep && start >= 0) {
      ranges.push([start, cp - 1]);
      start = -1;
    }
  }
}
ranges.sort((a, b) => a[0] - b[0]);
const merged = [];
for (const [s, e] of ranges) {
  const last = merged[merged.length - 1];
  if (last && s <= last[1] + 1) last[1] = Math.max(last[1], e);
  else merged.push([s, e]);
}
const total = merged.reduce((n, [s, e]) => n + e - s + 1, 0);

const hex = (n) => '0x' + n.toString(16).toUpperCase().padStart(4, '0');
const rows = [];
for (let i = 0; i < merged.length; i += 4) {
  rows.push('  ' + merged.slice(i, i + 4).map(([s, e]) => `${hex(s)}, ${hex(e)},`).join(' '));
}
const body = rows.join('\n');
const header = (c) => `${c} Generated by packages/canonical/scripts/generate-unicode.mjs from
${c} DerivedAge.txt, Unicode ${UNICODE_VERSION}. Do not edit by hand.
${c} ${merged.length} ranges, ${total} assigned code points.
${c} See apps/web/docs/decisions/0013-unicode-version.md.`;

const ts = `${header('//')}

/** The Unicode version canonicalisation is pinned to. */
export const UNICODE_VERSION = '${SHORT}';

/** Assigned code points in UNICODE_VERSION, as sorted inclusive [start, end] pairs. */
export const ASSIGNED_RANGES: readonly number[] = [
${body}
];
`;

const dart = `${header('//')}

/// The Unicode version canonicalisation is pinned to.
const unicodeVersion = '${SHORT}';

/// Assigned code points in [unicodeVersion], as sorted inclusive
/// [start, end] pairs.
const assignedRanges = <int>[
${body}
];
`;

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
writeFileSync(here('../src/unicode-assigned.ts'), ts);
writeFileSync(here('../../canonical_dart/lib/src/unicode_assigned.dart'), dart);
console.log(`Unicode ${UNICODE_VERSION}: ${merged.length} ranges, ${total} code points`);
