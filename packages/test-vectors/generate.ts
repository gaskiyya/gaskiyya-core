import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { canonicalise, canonicalReceipt, contentDigest, lagosDate, parseAmountToKobo, receiptDigest, ReceiptFieldError } from '@gaskiya/canonical';
import { amountCases, cases, differentDigestPairs, lagosDateCases, receiptCases, receiptDifferentPairs, receiptSameGroups, sameDigestGroups, type ReceiptCase } from './cases.ts';

function receiptVector(c: ReceiptCase) {
  try {
    const canonical = canonicalReceipt(c.fields);
    if (c.error) throw new Error(`${c.id}: expected an error on ${c.error}, got ${canonical}`);
    return { ...c, canonical, digest: receiptDigest(c.fields) };
  } catch (e) {
    if (!(e instanceof ReceiptFieldError)) throw e;
    if (e.field !== c.error) throw new Error(`${c.id}: expected an error on ${c.error ?? 'nothing'}, got one on ${e.field}`, { cause: e });
    return { ...c, canonical: null, digest: null };
  }
}

for (const a of amountCases) {
  const got = parseAmountToKobo(a.input);
  if (got !== a.kobo) throw new Error(`amount ${JSON.stringify(a.input)}: expected ${a.kobo}, got ${got}`);
}
for (const d of lagosDateCases) {
  if (lagosDate(new Date(d.instant)) !== d.date) throw new Error(`lagosDate ${d.instant}: expected ${d.date}`);
}

const out = {
  note: 'Generated by `pnpm vectors` from cases.ts. Do not edit by hand.',
  vectors: cases.map((c) => ({ ...c, canonical: canonicalise(c.input), digest: contentDigest(c.input) })),
  sameDigestGroups,
  differentDigestPairs,
  receipts: receiptCases.map(receiptVector),
  receiptSameGroups,
  receiptDifferentPairs,
  amounts: amountCases,
  lagosDates: lagosDateCases,
};
writeFileSync(fileURLToPath(new URL('./vectors.json', import.meta.url)), JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${out.vectors.length} message vectors and ${out.receipts.length} receipt vectors`);
